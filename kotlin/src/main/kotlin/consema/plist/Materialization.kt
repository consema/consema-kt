/** Stable materialization failure with the frozen code mapping
 * (materialization.rs). */
sealed class MaterializationFailure(val code: String) : Exception(code) {
    /** One complete input value cannot be represented; the payload names
     * the blocking fact. */
    data class Unrepresentable(val path: ValuePath, val kind: Kind) :
        MaterializationFailure(
            if (kind == Kind.Date) {
                PlistCodes.MATERIALIZATION_FRACTIONAL_DATE
            } else {
                PlistCodes.MATERIALIZATION_UNREPRESENTABLE
            },
        )

    /** Request fields contradict the record contract. */
    data class InvalidRequest(val reason: String) :
        MaterializationFailure("core.materialization.invalid-request@1")

    /** Target profile is unavailable. */
    data object UnsupportedProfile :
        MaterializationFailure("core.materialization.unsupported-profile@1")

    /** Style is unavailable for the target profile. */
    data object UnsupportedStyle :
        MaterializationFailure("core.materialization.unsupported-style@1")

    /** Encoding is unavailable for the target profile. */
    data object UnsupportedEncoding :
        MaterializationFailure("core.materialization.unsupported-encoding@1")

    /** Newline policy is unavailable for the selected style. */
    data object UnsupportedNewline :
        MaterializationFailure("core.materialization.unsupported-newline@1")

    /** A configured limit was reached. */
    data class ResourceLimit(val name: String) :
        MaterializationFailure(PlistCodes.MATERIALIZATION_RESOURCE_LIMIT)

    /** Generated bytes did not form the promised target document. */
    data object FormationFailed :
        MaterializationFailure("core.materialization.formation-failed@1")
}

/** One validated value record with its input path (materialization.rs
