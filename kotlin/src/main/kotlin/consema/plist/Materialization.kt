private class ValueNode(val path: ValuePath, val kind: ValueKind)

/** One validated dictionary association (materialization.rs). */
private class DictEntry(val key: PlistString, val keyPath: ValuePath, val value: ValueNode)

/** Closed validated value kinds (materialization.rs). */
private sealed class ValueKind {
    class Dict(val entries: List<DictEntry>) : ValueKind()

    class Array(val elements: List<ValueNode>) : ValueKind()

    class StringV(val string: PlistString) : ValueKind()

    class Integer(val value: Long) : ValueKind()

    class Real(val real: PlistReal) : ValueKind()

    class BooleanV(val value: Boolean) : ValueKind()

    class Date(val seconds: Double) : ValueKind()

    class Data(val bytes: ByteArray) : ValueKind()

    class Uid(val value: Int) : ValueKind()
}

/**
 * Materializes one complete `plist.value-tree@1` record into a new
 * immutable plist document (RFC 0013 §10; materialization.rs). A
 * failure contains no Document, no partial bytes, and no provenance that
 * can be mistaken for a result (RFC 0004 §3).
 */
fun materialize(
    value: PortableValue,
    request: MaterializationRequest,
): MaterializationResult<Document> {
    val analyzed = ArrayList<ValuePath>()
    return try {
        MaterializationResult.Complete(materializeComplete(value, request, analyzed))
    } catch (e: MaterializationFailure) {
        MaterializationResult.Failed(
            FailedMaterializationAttempt(
                failure = toDocumentException(e),
                report = MaterializationReport.new(emptyList(), request.limits),
                analyzedInputPaths = analyzed,
            ),
        )
    }
}

/**
 * The frozen `plist.materialization.*@1` failure-code mapping of one shared
 * materialization failure (materialization.rs). The family codes stay
 * out of the core registry (RFC 0013 §12), so the plist-specific codes are
 * carried in the exception [MaterializationException.reason] by
 * [toDocumentException]; this function restores the exact code the vectors
 * assert (plist_v1.rs).
 */
fun materializationFailureCode(failure: MaterializationException): String {
    if (failure.reason == PlistCodes.MATERIALIZATION_FRACTIONAL_DATE) {
        return PlistCodes.MATERIALIZATION_FRACTIONAL_DATE
    }
    if (failure.reason == PlistCodes.MATERIALIZATION_RESOURCE_LIMIT) {
        return PlistCodes.MATERIALIZATION_RESOURCE_LIMIT
    }
    return failure.code
}

/** Maps one family failure to the shared materialization exception carrying
 * the frozen code (the vector failure-name surface). */
private fun toDocumentException(failure: MaterializationFailure): MaterializationException =
    when (failure) {
        is MaterializationFailure.Unrepresentable -> MaterializationException(
            MaterializationFailureKind.UNREPRESENTABLE,
            reason = if (failure.kind == Kind.Date) {
                PlistCodes.MATERIALIZATION_FRACTIONAL_DATE
            } else {
                PlistCodes.MATERIALIZATION_UNREPRESENTABLE
            },
            path = failure.path,
            valueKind = failure.kind,
        )
        is MaterializationFailure.InvalidRequest -> MaterializationException(
            MaterializationFailureKind.INVALID_REQUEST,
            reason = failure.reason,
        )
        MaterializationFailure.UnsupportedProfile -> MaterializationException(
            MaterializationFailureKind.UNSUPPORTED_PROFILE,
        )
        MaterializationFailure.UnsupportedStyle -> MaterializationException(
            MaterializationFailureKind.UNSUPPORTED_STYLE,
        )
        MaterializationFailure.UnsupportedEncoding -> MaterializationException(
            MaterializationFailureKind.UNSUPPORTED_ENCODING,
        )
        MaterializationFailure.UnsupportedNewline -> MaterializationException(
            MaterializationFailureKind.UNSUPPORTED_NEWLINE,
        )
        is MaterializationFailure.ResourceLimit -> MaterializationException(
            MaterializationFailureKind.RESOURCE_LIMIT,
            reason = PlistCodes.MATERIALIZATION_RESOURCE_LIMIT,
            name = failure.name,
        )
        MaterializationFailure.FormationFailed -> MaterializationException(
            MaterializationFailureKind.FORMATION_FAILED,
        )
    }

private fun materializeComplete(
    value: PortableValue,
    request: MaterializationRequest,
    analyzed: ArrayList<ValuePath>,
): CompleteMaterialization<Document> {
    val style = validateRequest(request)
    val limits = request.limits
    val record = validateRecord(value, request, analyzed)
    // The transformed root carries the authorized truncations; the writers
    // serialize the transformed tree, never the raw input record
    // (materialization.rs mutates the record in place).
    val (promised, events, transformed) = buildNative(record, style)
    val (bytes, items) = when (style) {
        PlistMaterializationStyle.Xml -> serializeXml(promised, limits)
        PlistMaterializationStyle.Binary -> serializeBinary(promised, limits)
    }
    val profile = when (style) {
        PlistMaterializationStyle.Xml -> PlistProfile.XmlV1
        PlistMaterializationStyle.Binary -> PlistProfile.BinaryV1
    }
    val formed = try {
        parse(bytes, profile, PlistEncodingSelection.ProfileDefault, parseLimits(limits))
    } catch (e: PlistFormationException) {
        throw MaterializationFailure.FormationFailed
    }
    if (formed.formationStatus != consema.document.FormationStatus.Complete ||
        !nativeEquals(promised, formed)
    ) {
        throw MaterializationFailure.FormationFailed
    }
    // The truncation events are family diagnostics (`plist.materialization.
    // fractional-date@1` is not a core-registry code, RFC 0013 §12); they are
    // carried on the target document's family diagnostic list, following the
    // HCL family precedent of family-owned diagnostics
    // (kotlin/src/main/kotlin/consema/hcl/Errors.kt). The transferable `core.diagnostic@1`
    // form is produced by PlistDiagnostic.toProtocolDiagnostic when a caller
    // supplies a stable source ID and an error-code registry.
    val target = if (events.isEmpty()) {
        formed
    } else {
        val truncationDiagnostics = ArrayList<PlistDiagnostic>(events.size)
        for ((index, event) in events.withIndex()) {
            truncationDiagnostics.add(
                PlistDiagnostic(
                    code = PlistCodes.MATERIALIZATION_FRACTIONAL_DATE,
                    category = DiagnosticCategory.Materialization,
                    severity = Severity.Info,
                    startByte = null,
                    endByte = null,
                    arguments = event,
                    notes = emptyList(),
                    occurrence = formed.diagnosticsList.size.toLong() + index.toLong(),
                ),
            )
        }
        Document(
            authority = formed.authority,
            source = formed.source,
            profile = formed.profile,
            losslessIndex = formed.losslessStructuralIndex(),
            binaryIndex = formed.binaryStructuralIndex(),
            formationStatus = formed.formationStatus,
            diagnosticsList = formed.diagnosticsList + truncationDiagnostics,
            entities = formed.entities,
            rootIndex = formed.rootIndex,
            nativeRoot = formed.nativeRoot,
            syntaxKinds = formed.losslessSyntaxKinds(),
            binaryFacts = formed.binaryFacts(),
            parseLimits = formed.parseLimits,
        )
    }
    val provenance = buildProvenance(items, target, limits)
    return CompleteMaterialization(
        document = target,
        fidelity = if (transformed) MaterializationFidelity.Transformed else MaterializationFidelity.Exact,
        report = MaterializationReport.new(emptyList(), limits),
        provenance = provenance,
    )
}

/** Validates the request against the frozen style contracts (RFC 0013 §10;
 * materialization.rs). */
private fun validateRequest(request: MaterializationRequest): PlistMaterializationStyle {
    val profile = request.targetProfile
    val style = request.style
    val selected = when {
        profile.id == "plist.xml" && profile.version == 1 &&
            style.id == STYLE_XML && style.version == 1 -> PlistMaterializationStyle.Xml

        profile.id == "plist.binary" && profile.version == 1 &&
            style.id == STYLE_BINARY && style.version == 1 -> PlistMaterializationStyle.Binary

        (profile.id != "plist.xml" && profile.id != "plist.binary") || profile.version != 1 ->
            throw MaterializationFailure.UnsupportedProfile

        else -> throw MaterializationFailure.UnsupportedStyle
    }
    when (selected) {
        PlistMaterializationStyle.Xml -> {
            if (request.encoding !== SourceEncoding.Utf8) {
                throw MaterializationFailure.UnsupportedEncoding
            }
            if (request.newline != NewlinePolicy.Lf) {
                throw MaterializationFailure.UnsupportedNewline
            }
        }
        PlistMaterializationStyle.Binary -> {
            if (request.encoding !== SourceEncoding.Binary) {
                throw MaterializationFailure.UnsupportedEncoding
            }
            if (request.newline != NewlinePolicy.None) {
                throw MaterializationFailure.UnsupportedNewline
            }
        }
    }
    return selected
}

