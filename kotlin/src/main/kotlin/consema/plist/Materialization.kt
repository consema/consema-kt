private data class InputItem(val path: ValuePath, val target: Int)

private class XmlWriter(
    private val limits: MaterializationLimits,
    private val out: StringBuilder = StringBuilder(),
    private val items: ArrayList<InputItem> = ArrayList(),
) {
    private var rank = 0

    fun write(root: ValueNode): ByteArray {
        out.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
        out.append("<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n")
        out.append("<plist version=\"1.0\">\n")
        emitValue(root, 1)
        out.append("</plist>\n")
        checkOutput()
        return out.toString().toByteArray(Charsets.UTF_8)
    }

    private fun checkOutput() {
        if (out.length > limits.maxOutputBytes) {
            throw MaterializationFailure.ResourceLimit("output-bytes")
        }
    }

    private fun writeIndent(depth: Int) {
        repeat(depth) { out.append("    ") }
    }

    private fun emitValue(node: ValueNode, depth: Int) {
        when (val kind = node.kind) {
            is ValueKind.Dict -> {
                writeIndent(depth)
                if (kind.entries.isEmpty()) {
                    out.append("<dict></dict>\n")
                } else {
                    out.append("<dict>\n")
                    for (entry in kind.entries) {
                        writeIndent(depth + 1)
                        out.append("<key>")
                        escapeXmlText(entry.key.toUnicode()
                            ?: throw MaterializationFailure.Unrepresentable(entry.keyPath, Kind.String))
                        out.append("</key>\n")
                        emitValue(entry.value, depth + 1)
                    }
                    writeIndent(depth)
                    out.append("</dict>\n")
                }
            }
            is ValueKind.Array -> {
                writeIndent(depth)
                if (kind.elements.isEmpty()) {
                    out.append("<array></array>\n")
                } else {
                    out.append("<array>\n")
                    for (element in kind.elements) {
                        emitValue(element, depth + 1)
                    }
                    writeIndent(depth)
                    out.append("</array>\n")
                }
            }
            is ValueKind.StringV -> {
                writeIndent(depth)
                out.append("<string>")
                escapeXmlText(kind.string.toUnicode()
                    ?: throw MaterializationFailure.Unrepresentable(node.path, Kind.String))
                out.append("</string>\n")
            }
            is ValueKind.Integer -> {
                writeIndent(depth)
                out.append("<integer>")
                out.append(kind.value.toString())
                out.append("</integer>\n")
            }
            is ValueKind.Real -> {
                writeIndent(depth)
                out.append("<real>")
                out.append(renderReal(kind.real))
                out.append("</real>\n")
            }
            is ValueKind.BooleanV -> {
                writeIndent(depth)
                out.append(if (kind.value) "<true/>\n" else "<false/>\n")
            }
            is ValueKind.Date -> {
                writeIndent(depth)
                out.append("<date>")
                out.append(renderDate(wholeSecondDate(kind.seconds)
                    ?: throw MaterializationFailure.FormationFailed))
                out.append("</date>\n")
            }
            is ValueKind.Data -> {
                writeIndent(depth)
                out.append("<data>")
                out.append(encodeBase64Wrapped(kind.bytes, depth))
                out.append("</data>\n")
            }
            is ValueKind.Uid -> throw MaterializationFailure.FormationFailed
        }
        items.add(InputItem(node.path, rank))
        rank += 1
        checkOutput()
    }

    /** Escapes XML text content (RFC 0013 §4.9, §10.1): `&`, `<`, `>`, and a
     * literal CR (materialization.rs). */
    private fun escapeXmlText(text: String) {
        for (character in text) {
            when (character) {
                '&' -> out.append("&amp;")
                '<' -> out.append("&lt;")
                '>' -> out.append("&gt;")
                '\r' -> out.append("&#13;")
                else -> out.append(character)
            }
        }
    }

    /** Standard base64 with `=` padding wrapped at `76 - 8 * depth`
     * characters per line (RFC 0013 §4.8; materialization.rs). */
    private fun encodeBase64Wrapped(bytes: ByteArray, depth: Int): String {
        val budget = (76 - 8 * depth).coerceAtLeast(1)
        val alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
        val out2 = StringBuilder(bytes.size * 4 / 3 + 4)
        var line = 0
        var index = 0
        while (index < bytes.size) {
            val first = bytes[index].toInt() and 0xFF
            val second = if (index + 1 < bytes.size) bytes[index + 1].toInt() and 0xFF else 0
            val third = if (index + 2 < bytes.size) bytes[index + 2].toInt() and 0xFF else 0
            val chunkLen = minOf(3, bytes.size - index)
            if (line + 4 > budget && line > 0) {
                out2.append('\n')
                writeIndent(depth)
                line = 0
            }
            out2.append(alphabet[first ushr 2])
            out2.append(alphabet[((first and 0x03) shl 4) or (second ushr 4)])
            out2.append(if (chunkLen > 1) alphabet[((second and 0x0F) shl 2) or (third ushr 6)] else '=')
            out2.append(if (chunkLen > 2) alphabet[third and 0x3F] else '=')
            line += 4
            index += 3
        }
        return out2.toString()
    }

    fun items(): List<InputItem> = items
}

private fun serializeXml(root: ValueNode, limits: MaterializationLimits): Pair<ByteArray, List<InputItem>> {
    val writer = XmlWriter(limits)
    val bytes = writer.write(root)
    return bytes to writer.items()
}

