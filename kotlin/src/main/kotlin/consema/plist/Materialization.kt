/** One planned binary object; scalars are deduplicated at first occurrence
 * (materialization.rs). */
private sealed class PlannedObject {
    class Dict(val keys: MutableList<Int>, val values: MutableList<Int>) : PlannedObject()

    class Array(val elements: MutableList<Int>) : PlannedObject()

    class Scalar(val key: ScalarKey) : PlannedObject()
}

/** One scalar key of the dedup cache (materialization.rs). */
private sealed class ScalarKey {
    class StringV(val string: PlistString) : ScalarKey()

    class Integer(val value: Long) : ScalarKey()

    class Real(val real: PlistReal) : ScalarKey()

    class BooleanV(val value: Boolean) : ScalarKey()

    class Date(val bits: Long) : ScalarKey()

    class Data(val bytes: ByteArray) : ScalarKey()

    class Uid(val value: Int) : ScalarKey()

    /** Identical scalar objects (string, integer, real, date, data)
     * deduplicate (RFC 0013 §5.12). */
    fun deduplicates(): Boolean = this !is BooleanV && this !is Uid

    override fun equals(other: Any?): Boolean = when {
        this === other -> true
        other !is ScalarKey -> false
        this is StringV && other is StringV -> string == other.string
        this is Integer && other is Integer -> value == other.value
        this is Real && other is Real -> real == other.real
        this is BooleanV && other is BooleanV -> value == other.value
        this is Date && other is Date -> bits == other.bits
        this is Data && other is Data -> bytes.contentEquals(other.bytes)
        this is Uid && other is Uid -> value == other.value
        else -> false
    }

    override fun hashCode(): Int = when (this) {
        is StringV -> string.hashCode()
        is Integer -> value.hashCode()
        is Real -> real.hashCode()
        is BooleanV -> value.hashCode()
        is Date -> bits.hashCode()
        is Data -> bytes.contentHashCode()
        is Uid -> value.hashCode()
    }
}

private class BinaryPlan {
    val objects = ArrayList<PlannedObject>()
    val items = ArrayList<InputItem>()
}

private fun planBinary(root: ValueNode): BinaryPlan {
    fun planNode(node: ValueNode, plan: BinaryPlan, cache: HashMap<ScalarKey, Int>): Int {
        return when (val kind = node.kind) {
            is ValueKind.Dict -> {
                val index = plan.objects.size
                plan.objects.add(PlannedObject.Dict(ArrayList(), ArrayList()))
                plan.items.add(InputItem(node.path, index))
                val keyRefs = ArrayList<Int>(kind.entries.size)
                for (entry in kind.entries) {
                    val key = ScalarKey.StringV(entry.key)
                    val keyIndex = cache.getOrPut(key) {
                        val at = plan.objects.size
                        plan.objects.add(PlannedObject.Scalar(key))
                        at
                    }
                    keyRefs.add(keyIndex)
                }
                val valueRefs = ArrayList<Int>(kind.entries.size)
                for (entry in kind.entries) {
                    valueRefs.add(planNode(entry.value, plan, cache))
                }
                val dict = plan.objects[index] as PlannedObject.Dict
                dict.keys.addAll(keyRefs)
                dict.values.addAll(valueRefs)
                index
            }
            is ValueKind.Array -> {
                val index = plan.objects.size
                plan.objects.add(PlannedObject.Array(ArrayList()))
                plan.items.add(InputItem(node.path, index))
                val elements = plan.objects[index] as PlannedObject.Array
                for (element in kind.elements) {
                    elements.elements.add(planNode(element, plan, cache))
                }
                index
            }
            else -> {
                val key = scalarKeyOf(node)
                if (key.deduplicates()) {
                    cache[key]?.let { cached ->
                        plan.items.add(InputItem(node.path, cached))
                        return cached
                    }
                }
                val index = plan.objects.size
                plan.objects.add(PlannedObject.Scalar(key))
                if (key.deduplicates()) {
                    cache[key] = index
                }
                plan.items.add(InputItem(node.path, index))
                index
            }
        }
    }
    val plan = BinaryPlan()
    planNode(root, plan, HashMap())
    return plan
}

private fun scalarKeyOf(node: ValueNode): ScalarKey =
    when (val kind = node.kind) {
        is ValueKind.StringV -> ScalarKey.StringV(kind.string)
        is ValueKind.Integer -> ScalarKey.Integer(kind.value)
        is ValueKind.Real -> ScalarKey.Real(kind.real)
        is ValueKind.BooleanV -> ScalarKey.BooleanV(kind.value)
        is ValueKind.Date -> ScalarKey.Date(kind.seconds.toRawBits())
        is ValueKind.Data -> ScalarKey.Data(kind.bytes)
        is ValueKind.Uid -> ScalarKey.Uid(kind.value)
        else -> throw MaterializationFailure.FormationFailed
    }

private fun serializeBinary(root: ValueNode, limits: MaterializationLimits): Pair<ByteArray, List<InputItem>> {
    val plan = planBinary(root)
    val numObjects = plan.objects.size
    val refSize = refSizeFor(numObjects)
    val out = ArrayList<Byte>(8 + 1024)
    "bplist00".forEach { out.add(it.code.toByte()) }
    val offsets = ArrayList<Int>(numObjects)
    for (planned in plan.objects) {
        offsets.add(out.size)
        writePlannedObject(out, planned, refSize)
        if (out.size > limits.maxOutputBytes) {
            throw MaterializationFailure.ResourceLimit("output-bytes")
        }
    }
    val offsetTableOffset = out.size
    val offsetIntSize = refSizeFor(offsetTableOffset)
    for (offset in offsets) {
        writeBe(out, offset.toLong(), offsetIntSize)
    }
    repeat(5) { out.add(0) }
    out.add(0) // sortVersion
    out.add(offsetIntSize.toByte())
    out.add(refSize.toByte())
    writeBe(out, numObjects.toLong(), 8)
    writeBe(out, 0, 8) // topObject: the root value is always object 0
    writeBe(out, offsetTableOffset.toLong(), 8)
    return out.toByteArray() to plan.items
}

private fun writePlannedObject(out: ArrayList<Byte>, planned: PlannedObject, refSize: Int) {
    when (planned) {
        is PlannedObject.Dict -> {
            val count = planned.keys.size
            writeSized(out, 0xD0, count)
            for (key in planned.keys) {
                writeBe(out, key.toLong(), refSize)
            }
            for (entry in planned.values) {
                writeBe(out, entry.toLong(), refSize)
            }
        }
        is PlannedObject.Array -> {
            val count = planned.elements.size
            writeSized(out, 0xA0, count)
            for (element in planned.elements) {
                writeBe(out, element.toLong(), refSize)
            }
        }
        is PlannedObject.Scalar -> writeScalar(out, planned.key)
    }
}

private fun writeScalar(out: ArrayList<Byte>, key: ScalarKey) {
    when (key) {
        is ScalarKey.StringV -> writeStringObject(out, key.string)
        is ScalarKey.Integer -> {
            val width = integerWidth(key.value)
            out.add((0x10 or java.lang.Integer.numberOfTrailingZeros(width)).toByte())
            writeBe(out, key.value.toULong().toLong(), width)
        }
        is ScalarKey.Real -> when (key.real.width) {
            RealWidth.Float64 -> {
                out.add(0x23)
                writeBe(out, key.real.bits, 8)
            }
            RealWidth.Float32 -> {
                out.add(0x22)
                writeBe(out, key.real.bits, 4)
            }
        }
        is ScalarKey.BooleanV -> out.add(if (key.value) 0x09 else 0x08)
        is ScalarKey.Date -> {
            out.add(0x33)
            writeBe(out, key.bits, 8)
        }
        is ScalarKey.Data -> {
            writeSized(out, 0x40, key.bytes.size)
            for (byte in key.bytes) {
                out.add(byte)
            }
        }
        is ScalarKey.Uid -> {
            val value = key.value.toLong() and 0xFFFF_FFFFL
            val width = uidWidth(value)
            out.add((0x80 or (width - 1)).toByte())
            writeBe(out, value, width)
        }
    }
}

/** Writes one string object: the ASCII marker when every code unit is below
 * `0x80`, else the UTF-16BE marker (RFC 0013 §5.6; materialization.rs
 * 1541). */
private fun writeStringObject(out: ArrayList<Byte>, string: PlistString) {
    val units = string.codeUnits()
    if (units.all { it < 0x80 }) {
        writeSized(out, 0x50, units.size)
        for (unit in units) {
            out.add(unit.toByte())
        }
    } else {
        writeSized(out, 0x60, units.size)
        for (unit in units) {
            out.add((unit ushr 8).toByte())
            out.add(unit.toByte())
        }
    }
}

/** Writes one sized marker; counts of 15 or more use the extended-size
 * sentinel (RFC 0013 §5.4; materialization.rs). */
private fun writeSized(out: ArrayList<Byte>, marker: Int, count: Int) {
    if (count < 0x0F) {
        out.add((marker or count).toByte())
        return
    }
    out.add((marker or 0x0F).toByte())
    val width = unsignedWidth(count.toLong())
    out.add((0x10 or java.lang.Integer.numberOfTrailingZeros(width)).toByte())
    writeBe(out, count.toLong(), width)
}

/** Appends one big-endian unsigned value of exactly `width` bytes. */
private fun writeBe(out: ArrayList<Byte>, value: Long, width: Int) {
    for (shift in (0 until width).reversed()) {
        out.add(((value ushr (8 * shift)) and 0xFF).toByte())
    }
}

/** Smallest width in bytes whose capacity exceeds `maxIndex`
 * (materialization.rs). */
private fun refSizeFor(maxIndex: Int): Int {
    var size = 1
    var capacity = 256L
    while (maxIndex >= capacity && size < 8) {
        size += 1
        capacity = if (capacity > Long.MAX_VALUE / 256) Long.MAX_VALUE else capacity * 256
    }
    return size
}

/** Minimal marker width for one signed 64-bit integer: negatives always use
 * the signed 8-byte form (materialization.rs). */
private fun integerWidth(value: Long): Int =
    if (value >= 0) unsignedWidth(value) else 8

/** Minimal marker width for one unsigned count (materialization.rs
 * 1604). */
private fun unsignedWidth(value: Long): Int =
    when {
        value <= 0xFF -> 1
        value <= 0xFFFF -> 2
        value <= 0xFFFF_FFFFL -> 4
        else -> 8
    }

/** Minimal byte width of one unsigned 32-bit UID (materialization.rs
 * 1617). */
private fun uidWidth(value: Long): Int =
    when {
        value <= 0xFF -> 1
        value <= 0xFFFF -> 2
        value <= 0xFF_FFFF -> 3
        else -> 4
    }

