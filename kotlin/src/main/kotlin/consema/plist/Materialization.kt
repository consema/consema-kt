/** Compares the promised record tree against the reparsed target document
 * (RFC 0013 §10.3; materialization.rs). */
private fun nativeEquals(promised: ValueNode, document: Document): Boolean {
    val root = document.rootIndex
    return nativeNodeEquals(promised, document, root)
}

private fun nativeNodeEquals(node: ValueNode, document: Document, index: Int): Boolean {
    val native = document.valueEntity(index).native ?: return false
    return when (val kind = node.kind) {
        is ValueKind.Dict -> {
            val dict = native as? NativeValue.Dict ?: return false
            if (dict.entries.size != kind.entries.size) return false
            for ((position, entry) in kind.entries.withIndex()) {
                val entryEntity = document.dictEntryEntity(dict.entries[position])
                val keyNative = document.valueEntity(entryEntity.keyIndex).native
                    as? NativeValue.StringV ?: return false
                if (keyNative.string != entry.key) return false
                if (!nativeNodeEquals(entry.value, document, entryEntity.valueIndex)) return false
            }
            true
        }
        is ValueKind.Array -> {
            val array = native as? NativeValue.Array ?: return false
            if (array.elements.size != kind.elements.size) return false
            for ((position, element) in kind.elements.withIndex()) {
                val elementEntity = document.arrayElementEntity(array.elements[position])
                if (!nativeNodeEquals(element, document, elementEntity.valueIndex)) return false
            }
            true
        }
        is ValueKind.StringV -> {
            val string = native as? NativeValue.StringV ?: return false
            string.string == kind.string
        }
        is ValueKind.Integer -> native == NativeValue.Integer(kind.value)
        is ValueKind.Real -> native == NativeValue.Real(kind.real)
        is ValueKind.BooleanV -> native == NativeValue.BooleanV(kind.value)
        is ValueKind.Date -> native == NativeValue.Date(kind.seconds)
        is ValueKind.Data -> native == NativeValue.Data(PlistData.fromBytes(kind.bytes))
        is ValueKind.Uid -> native == NativeValue.Uid(PlistUid(kind.value))
    }
}

/** Builds the input-to-target provenance map (RFC 0004 §8;
 * materialization.rs). The item target is the post-order rank of
 * the emitted value (materialization.rs): for the XML profile the
 * rank runs over value-only entities in close order (dict keys are
 * excluded), and for the binary profile it is the object-table index. */
private fun buildProvenance(
    items: List<InputItem>,
    document: Document,
    limits: MaterializationLimits,
): MaterializationProvenanceMap {
    val valueIndices = document.entities.indices.filter {
        (document.entities[it] as? Entity.Value)?.entity?.isKey == false
    }
    val entries = ArrayList<MaterializationProvenanceEntry>()
    for (item in items) {
        val index = valueIndices.getOrNull(item.target) ?: continue
        val entity = (document.entities[index] as Entity.Value).entity
        entries.add(
            MaterializationProvenanceEntry(
                input = MaterializationInputLocation.Value(item.path),
                outputs = listOf(
                    MaterializedOrigin(
                        snapshot = document.snapshotIdentity,
                        node = document.nodeRef(index.toLong(), consema.document.NodeRole.PlistValue),
                        span = entity.span,
                        relation = MaterializationRelation.Direct,
                    ),
                ),
            ),
        )
    }
    return MaterializationProvenanceMap.new(entries, document.snapshotIdentity, limits)
}

/** The sign bit of one double (true for -0.0, -inf, and negatives). */
private fun negativeSign(value: Double): Boolean =
    java.lang.Double.doubleToRawLongBits(value) < 0

/** Exact signed 64-bit conversion of one portable integer; null when the magnitude exceeds the range. */
private fun bigIntegerToLong(value: java.math.BigInteger): Long? =
    try {
        value.toLong()
    } catch (e: NumberFormatException) {
        null
    }

/** Truncation toward zero (the fractional-date truncation policy). */
private fun truncTowardZero(value: Double): Double =
    if (value >= 0.0) java.lang.Math.floor(value) else java.lang.Math.ceil(value)
