/** Validates the record shape, the truncation policy, and the value tree
 * (materialization.rs). */
private fun validateRecord(
    value: PortableValue,
    request: MaterializationRequest,
    analyzed: ArrayList<ValuePath>,
): Record {
    analyzed.add(ValuePath.root())
    val objectValue = value as? PvObject
        ?: throw MaterializationFailure.InvalidRequest("input record is not plist.value-tree@1")
    val entries = objectValue.entries()
    if (entries.isEmpty() || entries[0].key != "record") {
        throw MaterializationFailure.InvalidRequest("input record is not plist.value-tree@1")
    }
    val recordValue = entries[0].value as? PvString
        ?: throw MaterializationFailure.InvalidRequest("input record is not plist.value-tree@1")
    if (recordValue.value != VALUE_TREE_RECORD) {
        throw MaterializationFailure.InvalidRequest("input record is not plist.value-tree@1")
    }
    val rootEntry = entries.firstOrNull { it.key == "root" }
        ?: throw MaterializationFailure.InvalidRequest("input record is not plist.value-tree@1")
    val policyEntry = entries.firstOrNull { it.key == "truncate_policy" }
    val policy = if (policyEntry == null) {
        false
    } else {
        val policyValue = policyEntry.value as? PvString
            ?: throw MaterializationFailure.Unrepresentable(
                ValuePath.root(), policyEntry.value.kind,
            )
        if (policyValue.value != TRUNCATE_POLICY) {
            throw MaterializationFailure.InvalidRequest("unsupported truncate policy")
        }
        true
    }
    val rootPath = ValuePath.root().child(ValuePathSegment.ObjectValue("root"))
    val root = validateValue(rootEntry.value, rootPath, request.limits, analyzed, 0)
    return Record(root, policy)
}

/** One validated `plist.value-tree@1` record (materialization.rs). */
private class Record(val root: ValueNode, val policy: Boolean)

private fun validateValue(
    value: PortableValue,
    path: ValuePath,
    limits: MaterializationLimits,
    analyzed: ArrayList<ValuePath>,
    depth: Int,
): ValueNode = ValueNode(path, validateKind(value, path, limits, analyzed, depth))

private fun validateKind(
    value: PortableValue,
    path: ValuePath,
    limits: MaterializationLimits,
    analyzed: ArrayList<ValuePath>,
    depth: Int,
): ValueKind {
    analyzed.add(path)
    val maxOutputBytes = limits.maxOutputBytes
    val kind: ValueKind = when (value) {
        is PvObject -> {
            val objectEntries = value.entries()
            if (objectEntries.any { it.key == "kind" }) {
                throw MaterializationFailure.Unrepresentable(path, Kind.Object)
            }
            val epoch = objectEntries.firstOrNull { it.key == "epoch" }
            val seconds = objectEntries.firstOrNull { it.key == "seconds" }
            if (epoch != null && seconds != null) {
                // Date leaf: exact double seconds plus the fixed epoch.
                val epochValue = epoch.value as? PvString
                    ?: throw MaterializationFailure.Unrepresentable(
                        path.child(ValuePathSegment.ObjectValue("epoch")), epoch.value.kind,
                    )
                if (epochValue.value != PLIST_EPOCH_SPELLING) {
                    throw MaterializationFailure.InvalidRequest(
                        "date epoch is not 2001-01-01T00:00:00Z",
                    )
                }
                val secondsValue = when (val member = seconds.value) {
                    is PvBinaryFloat64 -> member.toFloat()
                    is PvDecimal -> decimalToF64(member)
                        ?: throw MaterializationFailure.Unrepresentable(path, Kind.Date)
                    else -> throw MaterializationFailure.Unrepresentable(path, Kind.Date)
                }
                if (!secondsValue.isFinite()) {
                    throw MaterializationFailure.Unrepresentable(path, Kind.Date)
                }
                ValueKind.Date(secondsValue)
            } else {
                val uid = objectEntries.firstOrNull { it.key == "uid" }
                if (uid != null) {
                    val integer = uid.value as? PvInteger
                        ?: throw MaterializationFailure.Unrepresentable(
                            path.child(ValuePathSegment.ObjectValue("uid")), uid.value.kind,
                        )
                    val long = bigIntegerToLong(integer.value)
                        ?: throw MaterializationFailure.Unrepresentable(path, Kind.Integer)
                    val uidValue = long.toInt().takeIf { long in 0..0xFFFF_FFFFL }
                        ?: throw MaterializationFailure.Unrepresentable(path, Kind.Integer)
                    ValueKind.Uid(uidValue)
                } else {
                    val hex = objectEntries.firstOrNull { it.key == "hex" }
                    if (hex != null) {
                        val hexText = hex.value as? PvString
                            ?: throw MaterializationFailure.Unrepresentable(
                                path.child(ValuePathSegment.ObjectValue("hex")), hex.value.kind,
                            )
                        if (hexText.value.length / 2 > maxOutputBytes) {
                            throw MaterializationFailure.ResourceLimit("output-bytes")
                        }
                        val bytes = decodeHex(hexText.value)
                            ?: throw MaterializationFailure.Unrepresentable(path, Kind.String)
                        ValueKind.Data(bytes)
                    } else {
                        // A dictionary spelled as an ordered JSON object.
                        if (depth + 1 > limits.maxDepth) {
                            throw MaterializationFailure.ResourceLimit("input-depth")
                        }
                        val out = ArrayList<DictEntry>(objectEntries.size)
                        for ((ordinal, entry) in objectEntries.withIndex()) {
                            val keyPath = path.child(ValuePathSegment.EntryKey(ordinal.toLong()))
                            val valuePath = path.child(ValuePathSegment.EntryValue(ordinal.toLong()))
                            out.add(
                                DictEntry(
                                    PlistString.fromUnicode(entry.key),
                                    keyPath,
                                    validateValue(entry.value, valuePath, limits, analyzed, depth + 1),
                                ),
                            )
                        }
                        ValueKind.Dict(out)
                    }
                }
            }
        }
        is PvArray -> {
            if (depth + 1 > limits.maxDepth) {
                throw MaterializationFailure.ResourceLimit("input-depth")
            }
            val out = ArrayList<ValueNode>(value.items().size)
            for ((index, element) in value.items().withIndex()) {
                val elementPath = path.child(ValuePathSegment.SequenceElement(index.toLong()))
                out.add(validateValue(element, elementPath, limits, analyzed, depth + 1))
            }
            ValueKind.Array(out)
        }
        is PvEntryMapping -> {
            // Ordered dictionary associations; the projection emission keeps
            // duplicate keys and association order (RFC 0013 §9;
            // materialization.rs).
            if (depth + 1 > limits.maxDepth) {
                throw MaterializationFailure.ResourceLimit("input-depth")
            }
            val out = ArrayList<DictEntry>(value.size())
            for ((ordinal, entry) in value.entries().withIndex()) {
                val keyPath = path.child(ValuePathSegment.EntryKey(ordinal.toLong()))
                val key = entry.key as? PvString
                    ?: throw MaterializationFailure.Unrepresentable(keyPath, entry.key.kind)
                val valuePath = path.child(ValuePathSegment.EntryValue(ordinal.toLong()))
                out.add(
                    DictEntry(
                        PlistString.fromUnicode(key.value),
                        keyPath,
                        validateValue(entry.value, valuePath, limits, analyzed, depth + 1),
                    ),
                )
            }
            ValueKind.Dict(out)
        }
        is PvString -> {
            if (value.value.length > maxOutputBytes) {
                throw MaterializationFailure.ResourceLimit("output-bytes")
            }
            ValueKind.StringV(PlistString.fromUnicode(value.value))
        }
        is PvInteger -> {
            val long = bigIntegerToLong(value.value)
                ?: throw MaterializationFailure.Unrepresentable(path, Kind.Integer)
            ValueKind.Integer(long)
        }
        is PvBinaryFloat32 -> ValueKind.Real(PlistReal.single(value.bits))
        is PvBinaryFloat64 -> ValueKind.Real(PlistReal.double(value.bits))
        is PvDecimal -> {
            val real = decimalToF64(value)
                ?: throw MaterializationFailure.Unrepresentable(path, Kind.Decimal)
            ValueKind.Real(PlistReal.double(real.toBits()))
        }
        is PvBoolean -> ValueKind.BooleanV(value.value)
        is PvBytes -> {
            if (value.content().size > maxOutputBytes) {
                throw MaterializationFailure.ResourceLimit("output-bytes")
            }
            ValueKind.Data(value.content())
        }
        else -> throw MaterializationFailure.Unrepresentable(path, value.kind)
    }
    return kind
}

/** Converts one exact decimal to its double value; null when the
 * coefficient or exponent exceeds the exact i64 range (materialization.rs
 *). */
private fun decimalToF64(decimal: PvDecimal): Double? {
    val coefficient = bigIntegerToLong(decimal.coefficient) ?: return null
    val exponent = bigIntegerToLong(decimal.exponent) ?: return null
    var value = coefficient.toDouble()
    if (exponent >= 0) {
        for (i in 0 until exponent.toInt().coerceAtMost(400)) {
            value *= 10.0
        }
    } else {
        for (i in 0 until (-exponent).toInt().coerceAtMost(400)) {
            value /= 10.0
        }
    }
    return value
}

/** Builds the promised native model with the style expressibility rules
 * (RFC 0013 §7, §10; materialization.rs). Returns the record tree,
 * the truncation events, and whether the operation was transformed. */
private fun buildNative(
    record: Record,
    style: PlistMaterializationStyle,
): Triple<ValueNode, List<Map<String, String>>, Boolean> {
    val events = ArrayList<Map<String, String>>()
    var transformed = false
    val root = buildValue(record.root, style, record.policy, events, transformedRef = { transformed = it })
    return Triple(root, events, transformed)
}

private fun buildValue(
    node: ValueNode,
    style: PlistMaterializationStyle,
    policy: Boolean,
    events: ArrayList<Map<String, String>>,
    transformedRef: (Boolean) -> Unit,
): ValueNode {
    val kind = when (val kind = node.kind) {
        is ValueKind.Dict -> {
            val entries = kind.entries.map { entry ->
                if (style == PlistMaterializationStyle.Xml && !isXmlText(entry.key.codeUnits())) {
                    throw MaterializationFailure.Unrepresentable(entry.keyPath, Kind.String)
                }
                DictEntry(
                    entry.key,
                    entry.keyPath,
                    buildValue(entry.value, style, policy, events, transformedRef),
                )
            }
            ValueKind.Dict(entries)
        }
        is ValueKind.Array -> {
            val elements = kind.elements.map {
                buildValue(it, style, policy, events, transformedRef)
            }
            ValueKind.Array(elements)
        }
        is ValueKind.StringV -> {
            if (style == PlistMaterializationStyle.Xml &&
                (kind.string.status == PlistStringStatus.UnpairedSurrogate ||
                    !isXmlText(kind.string.codeUnits()))
            ) {
                throw MaterializationFailure.Unrepresentable(node.path, Kind.String)
            }
            kind
        }
        is ValueKind.Integer -> kind
        is ValueKind.Real -> {
            if (style == PlistMaterializationStyle.Xml) {
                if (kind.real.width == RealWidth.Float32) {
                    throw MaterializationFailure.Unrepresentable(node.path, Kind.BinaryFloat32)
                }
                if (!realExpressible(kind.real)) {
                    throw MaterializationFailure.Unrepresentable(node.path, Kind.BinaryFloat64)
                }
            }
            kind
        }
        is ValueKind.BooleanV -> kind
        is ValueKind.Date -> {
            if (style == PlistMaterializationStyle.Xml) {
                if (kind.seconds.toRawBits() == NEGATIVE_ZERO_BITS) {
                    throw MaterializationFailure.Unrepresentable(node.path, Kind.Date)
                }
                val whole = wholeSecondDate(kind.seconds)
                if (whole == null) {
                    if (!policy) {
                        throw MaterializationFailure.Unrepresentable(node.path, Kind.Date)
                    }
                    val original = kind.seconds
                    val truncated = truncTowardZero(original)
                    if (truncated.toRawBits() == NEGATIVE_ZERO_BITS || wholeSecondDate(truncated) == null) {
                        throw MaterializationFailure.Unrepresentable(node.path, Kind.Date)
                    }
                    events.add(
                        mapOf(
                            "path" to node.path.toString(),
                            "original" to original.toString(),
                            "truncated" to truncated.toString(),
                        ),
                    )
                    transformedRef(true)
                    ValueKind.Date(truncated)
                } else {
                    kind
                }
            } else {
                kind
            }
        }
        is ValueKind.Data -> kind
        is ValueKind.Uid -> {
            if (style == PlistMaterializationStyle.Xml) {
                throw MaterializationFailure.Unrepresentable(node.path, Kind.BinaryFloat32)
            }
            kind
        }
    }
    return ValueNode(node.path, kind)
}

/** Whether the exact bits of one real survive the XML spelling
 * (materialization.rs). */
private fun realExpressible(real: PlistReal): Boolean {
    val value = real.asDouble()
    return if (value.isNaN()) {
        value.toRawBits() == java.lang.Double.doubleToRawLongBits(Double.NaN)
    } else if (value.isInfinite()) {
        true
    } else {
        value.toString().toDoubleOrNull()?.toRawBits() == value.toRawBits()
    }
}

/** Whether every scalar of one well-formed UTF-16 sequence is an XML 1.0
 * character (materialization.rs). */
private fun isXmlText(units: IntArray): Boolean {
    var index = 0
    while (index < units.size) {
        val unit = units[index]
        val scalar = if (unit in 0xD800..0xDBFF) {
            if (index + 1 < units.size && units[index + 1] in 0xDC00..0xDFFF) {
                index += 2
                0x1_0000 + ((unit - 0xD800) shl 10) + (units[index - 1] - 0xDC00)
            } else {
                return false
            }
        } else if (unit in 0xDC00..0xDFFF) {
            return false
        } else {
            index += 1
            unit
        }
        if (scalar != 0x9 && scalar != 0xA && scalar != 0xD &&
            !(scalar in 0x20..0xD7FF) && !(scalar in 0xE000..0xFFFD) &&
            !(scalar in 0x1_0000..0x10_FFFF)
        ) {
            return false
        }
    }
    return true
}

/** Decomposes exact plist-epoch seconds into XML calendar fields
 * (materialization.rs). */
private fun wholeSecondDate(seconds: Double): DateFields? {
    if (seconds % 1.0 != 0.0) {
        return null
    }
    val unix = seconds + PLIST_EPOCH_OFFSET_UNIX
    if (kotlin.math.abs(unix) >= EXACT_UNIX_SECONDS_BOUND) {
        return null
    }
    val unixInt = unix.toLong()
    val days = Math.floorDiv(unixInt, 86_400L)
    val secondsOfDay = Math.floorMod(unixInt, 86_400L)
    val (year, month, day) = civilFromDays(days)
    if (year.absoluteValue > 0xFFFF_FFFFL) {
        return null
    }
    return DateFields(
        year = year,
        month = month,
        day = day,
        hour = secondsOfDay / 3_600,
        minute = (secondsOfDay % 3_600) / 60,
        second = secondsOfDay % 60,
    )
}

private data class DateFields(val year: Long, val month: Long, val day: Long, val hour: Long, val minute: Long, val second: Long)

/** Proleptic Gregorian calendar date of `days` since the Unix epoch
 * (materialization.rs). */
private fun civilFromDays(days: Long): Triple<Long, Long, Long> {
    val z = days + 719_468
    val era = if (z >= 0) z else z - 146_096
    val eraNormalized = era / 146_097
    val dayOfEra = z - eraNormalized * 146_097
    val yearOfEra =
        (dayOfEra - dayOfEra / 1_460 + dayOfEra / 36_524 - dayOfEra / 146_096) / 365
    var year = yearOfEra + eraNormalized * 400
    val dayOfYear = dayOfEra - (365 * yearOfEra + yearOfEra / 4 - yearOfEra / 100)
    val monthPrime = (5 * dayOfYear + 2) / 153
    val day = dayOfYear - (153 * monthPrime + 2) / 5 + 1
    val month = monthPrime + if (monthPrime < 10) 3 else -9
    year += if (month <= 2) 1 else 0
    return Triple(year, month, day)
}

/** Whole-second XML date spelling (RFC 0013 §4.7; materialization.rs
 * 1275). */
private fun renderDate(fields: DateFields): String {
    val sign = if (fields.year < 0) "-" else ""
    return String.format(
        java.util.Locale.ROOT,
        "%s%04d-%02d-%02dT%02d:%02d:%02dZ",
        sign, fields.year.absoluteValue, fields.month, fields.day,
        fields.hour, fields.minute, fields.second,
    )
}

/** Deterministic shortest-round-trip decimal spelling of one real
 * (materialization.rs). */
private fun renderReal(real: PlistReal): String {
    val value = real.asDouble()
    return when {
        value.isNaN() -> "nan"
        value.isInfinite() -> if (negativeSign(value)) "-inf" else "inf"
        else -> value.toString()
    }
}

/** Hex decode of the data-leaf vector spelling; null on malformed hex. */
private fun decodeHex(hex: String): ByteArray? {
    if (hex.length % 2 != 0) {
        return null
    }
    val output = ByteArray(hex.length / 2)
    for (index in output.indices) {
        val high = hex[index * 2].digitToIntOrNull(16) ?: return null
        val low = hex[index * 2 + 1].digitToIntOrNull(16) ?: return null
        output[index] = ((high shl 4) or low).toByte()
    }
    return output
}

