// Deterministic PortableValue materialization for the plist profiles, plus
// the cross-representation conversion transform.
//
// Data authority:
//   - RFC 0004 §3-§8 (https://github.com/consema/consema/blob/main/docs/rfcs/0004-materialization-conversion-and-
//     structural-edit-v1.md): the common MaterializationRequest v1,
//     ExactOnly representability, the completion algebra, and the
//     provenance direction (portable input locations to the new Document).
//   - RFC 0013 §10 (https://github.com/consema/consema/blob/main/docs/rfcs/0013-plist-family-profiles-v1.md):
//     `plist.xml-canonical@1` (Apple header spelling, four-space
//     indentation, LF line endings, whole-second dates, base64 wrapped at
//     `76 - 8 * depth`, decimal integers, shortest-round-trip reals) and
//     `plist.binary-canonical@1` (minimal widths, negatives always 8 bytes,
//     Float32 width preserved, deduplicated scalars, minimal ref/offset
//     widths, sortVersion 0). Every style validates the complete input,
//     encodes, reparses the exact generated bytes, and compares the reparsed
//     native model to the promised input semantics.
//   - RFC 0013 §7 (https://github.com/consema/consema/blob/main/docs/rfcs/0013-plist-family-profiles-v1.md): conversion between the two
//     representations is exact when every native fact is expressible and
//     fails atomically otherwise; binary-only facts are UID values, Float32
//     width facts, unpaired-surrogate strings, fractional-second dates, and
//     shared object identity.
//   - conformance/vectors/plist-v1.json (plist.materialization.*,
//     plist.conversion.*) pins the golden output bytes and failure codes;
//     https://github.com/consema/consema-rs/blob/main/consema-plist/src/materialization.rs is the byte-arbitration
//     authority (record validation materialization.rs, expressibility
//     materialization.rs, XML writer materialization.rs,
//     binary writer materialization.rs);
//     document.rs pins the conversion transform.
//
// Kotlin-idiomatic design: a bounded output buffer wraps the JDK byte
// accumulation with explicit checked growth; the writers are single
// recursive classes with exhaustive `when` over the closed PortableValue
// kind set (the json-family precedent, kotlin/src/main/kotlin/consema/json/Materialization.kt).

