/** One matched output origin in the reparsed document (materialization.rs:
 * 902-907). */
private class OutputItem(
    val node: NodeRef,
    val span: Span,
    val relation: MaterializationRelation,
)

/**
 * Walks the input record and the reparsed document in lockstep, compares
 * the promised semantics, and pairs every recorded input location with its
 * exact output origin. Any mismatch fails the whole materialization
 * (materialization.rs:909-1100).
 */
private fun verifyClosure(
    input: XmlRecord,
    document: Document,
    items: List<InputItem>,
    limits: MaterializationLimits,
): MaterializationProvenanceMap {
    val outputs = ArrayList<OutputItem>()
    val root = document.root() ?: throw MaterializationException(
        MaterializationFailureKind.FORMATION_FAILED,
    )
    // Declaration closure.
    when {
        input.declaration == null && document.declaration() == null -> {}
        input.declaration != null && document.declaration() != null -> {
            val declared = input.declaration!!
            val reparsed = document.declaration()!!
            if (reparsed.version != declared.version ||
                reparsed.standalone?.second != declared.standalone
            ) {
                throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
            }
        }
        else -> throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
    }
    // Entity closure.
    val reparsedDoctype = document.doctype()
    if (reparsedDoctype != null) {
        if (reparsedDoctype.entities.size != input.entities.size ||
            reparsedDoctype.entities.zip(input.entities).any { (reparsed, declared) ->
                reparsed.name != declared.name || reparsed.replacement != declared.replacement
            }
        ) {
            throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
        }
    } else if (input.entities.isNotEmpty()) {
        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
    }
    // Declaration and entity outputs precede the tree walk, matching the
    // generation order of their input items.
    if (input.declaration != null) {
        val declared = document.declaration() ?: throw MaterializationException(
            MaterializationFailureKind.FORMATION_FAILED,
        )
        outputs.add(
            OutputItem(
                document.authority.nodeRef(1, NodeRole.XmlDeclaration),
                declared.span,
                MaterializationRelation.Direct,
            ),
        )
    }
    reparsedDoctype?.let { doctype ->
        for (entity in doctype.entities) {
            outputs.add(
                OutputItem(
                    document.authority.nodeRef(2, NodeRole.XmlDoctype),
                    entity.span,
                    MaterializationRelation.Direct,
                ),
            )
        }
    }
    val context = ClosureContext(document, outputs, limits)
    context.element(input.root, root)
    // Pair input items with outputs by traversal order; adjacent items with
    // the same input location share one provenance entry.
    if (outputs.size != items.size) {
        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
    }
    val entries = ArrayList<MaterializationProvenanceEntry>()
    for ((item, output) in items.zip(outputs)) {
        val location = item.location()
        val origin = MaterializedOrigin(
            snapshot = document.snapshotIdentity,
            node = output.node,
            span = output.span,
            relation = output.relation,
        )
        val previous = entries.lastOrNull()
        if (previous != null && previous.input == location) {
            entries[entries.size - 1] = MaterializationProvenanceEntry(
                location,
                previous.outputs + origin,
            )
        } else {
            entries.add(MaterializationProvenanceEntry(location, listOf(origin)))
        }
    }
    return MaterializationProvenanceMap.new(entries, document.snapshotIdentity, limits)
}

/** One element closure walk over the reparsed document
 * (materialization.rs:1016-1210). */
private class ClosureContext(
    private val document: Document,
    private val outputs: MutableList<OutputItem>,
    private val limits: MaterializationLimits,
) {
    private fun push(node: NodeRef, span: Span, relation: MaterializationRelation) {
        if (outputs.size >= limits.maxProvenanceEntries) {
            throw MaterializationException(
                MaterializationFailureKind.RESOURCE_LIMIT,
                name = "provenance-entries",
            )
        }
        outputs.add(OutputItem(node, span, relation))
    }

    fun element(input: XmlElementRecord, reparsed: XmlElement) {
        val data = document.elementData(reparsed.index)
        // The element output precedes the namespace and attribute outputs,
        // matching the generation order of the writer's input items.
        push(reparsed.nodeRef(), data.span, MaterializationRelation.Direct)
        val expanded = data.expanded
            ?: throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
        val nameMatches = when {
            input.namespace != null && expanded.namespace != null ->
                input.namespace == expanded.namespace

            input.namespace == null && expanded.namespace == null -> true
            else -> false
        }
        if (!nameMatches || expanded.local != input.local) {
            throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
        }
        for (binding in data.namespaces) {
            push(
                document.authority.nodeRef(binding.ordinal, NodeRole.XmlNamespaceBinding),
                binding.span,
                MaterializationRelation.Generated,
            )
        }
        val attributes = data.attributes
        if (attributes.size != input.attributes.size) {
            throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
        }
        for ((inputAttribute, attribute) in input.attributes.zip(attributes)) {
            push(
                document.authority.nodeRef(attribute.ordinal, NodeRole.XmlAttribute),
                attribute.span,
                MaterializationRelation.Direct,
            )
            val expandedAttribute = attribute.expanded
                ?: throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
            val attrNameMatches = when {
                inputAttribute.namespace != null && expandedAttribute.namespace != null ->
                    inputAttribute.namespace == expandedAttribute.namespace

                inputAttribute.namespace == null && expandedAttribute.namespace == null -> true
                else -> false
            }
            if (!attrNameMatches ||
                expandedAttribute.local != inputAttribute.local ||
                attribute.normalizedValue != inputAttribute.value
            ) {
                throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
            }
        }
        val children = data.children
        if (children.size != input.content.size) {
            throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
        }
        for ((contentInput, childIndex) in input.content.zip(children)) {
            val child = XmlContentItem(document, childIndex)
            when (contentInput) {
                is ContentRecord.Element -> {
                    val childElement = child.element()
                        ?: throw MaterializationException(
                            MaterializationFailureKind.FORMATION_FAILED,
                        )
                    element(contentInput.element, childElement)
                }
                is ContentRecord.Text -> {
                    val text = child.text()
                        ?: throw MaterializationException(
                            MaterializationFailureKind.FORMATION_FAILED,
                        )
                    push(
                        document.authority.nodeRef(text.ordinal, NodeRole.XmlText),
                        text.span,
                        MaterializationRelation.Direct,
                    )
                    var semantic = StringBuilder()
                    for (fragment in contentInput.fragments) {
                        when (fragment) {
                            is FragmentRecord.Literal -> pushNormalized(semantic, fragment.text)
                            is FragmentRecord.CharacterReference ->
                                semantic.append(fragment.resolved)

                            is FragmentRecord.PredefinedEntity,
                            is FragmentRecord.GeneralEntity,
                            -> pushNormalized(
                                semantic,
                                (fragment as? FragmentRecord.PredefinedEntity)
                                    ?.resolved
                                    ?: (fragment as FragmentRecord.GeneralEntity).resolved,
                            )
                        }
                        push(
                            document.authority.nodeRef(text.ordinal, NodeRole.XmlEntityReference),
                            text.fragments.firstOrNull()?.span ?: text.span,
                            MaterializationRelation.Direct,
                        )
                    }
                    if (textSemantic(text) != semantic.toString()) {
                        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
                    }
                }
                is ContentRecord.Cdata -> {
                    val cdata = child.cdata()
                        ?: throw MaterializationException(
                            MaterializationFailureKind.FORMATION_FAILED,
                        )
                    push(
                        document.authority.nodeRef(cdata.ordinal, NodeRole.XmlCdata),
                        cdata.span,
                        MaterializationRelation.Direct,
                    )
                    if (cdata.text != contentInput.text) {
                        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
                    }
                }
                is ContentRecord.Comment -> {
                    val comment = child.comment()
                        ?: throw MaterializationException(
                            MaterializationFailureKind.FORMATION_FAILED,
                        )
                    push(
                        document.authority.nodeRef(comment.ordinal, NodeRole.XmlComment),
                        comment.span,
                        MaterializationRelation.Direct,
                    )
                    if (comment.text != contentInput.text) {
                        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
                    }
                }
                is ContentRecord.ProcessingInstruction -> {
                    val pi = child.processingInstruction()
                        ?: throw MaterializationException(
                            MaterializationFailureKind.FORMATION_FAILED,
                        )
                    push(
                        document.authority.nodeRef(pi.ordinal, NodeRole.XmlProcessingInstruction),
                        pi.span,
                        MaterializationRelation.Direct,
                    )
                    if (pi.target != contentInput.target ||
                        pi.content?.second != contentInput.content
                    ) {
                        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
                    }
                }
            }
        }
    }
}

/** XML 1.0 line-end normalization for one fragment: CRLF and CR become LF
 * (materialization.rs:1212-1226). */
private fun pushNormalized(out: StringBuilder, text: String) {
    var index = 0
    while (index < text.length) {
        val c = text[index]
        when (c) {
            '\r' -> {
                out.append('\n')
                if (index + 1 < text.length && text[index + 1] == '\n') {
                    index += 1
                }
            }
            else -> out.append(c)
        }
        index += 1
    }
}
