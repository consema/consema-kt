/** Strict record validation (materialization.rs:238-500). */
private object Record {
    fun validate(value: PortableValue, analyzed: MutableList<ValuePath>): XmlRecord {
        analyzed.add(ValuePath.root())
        val rootPath = ValuePath.root().child(ValuePathSegment.ObjectValue("root"))
        val record = expectStringField(value, "record", ValuePath.root())
        if (record != "xml.element-tree@1") {
            throw MaterializationException(
                MaterializationFailureKind.INVALID_REQUEST,
                reason = "input record is not xml.element-tree@1",
            )
        }
        val rootValue = expectField(value, "root", rootPath)
        val declaration = when (val pair = expectOptionalObjectField(value, "declaration")) {
            null -> null
            else -> {
                val (declarationValue, path) = pair
                val version = expectStringField(declarationValue, "version", path)
                if (version != "1.0") {
                    throw MaterializationException(
                        MaterializationFailureKind.UNREPRESENTABLE,
                        path = path.child(ValuePathSegment.ObjectValue("version")),
                        valueKind = consema.core.Kind.String,
                    )
                }
                val encoding = expectOptionalStringField(declarationValue, "encoding", path)
                val standalone = expectOptionalBooleanField(declarationValue, "standalone", path)
                DeclarationRecord(version, encoding, standalone, path)
            }
        }
        val entities = when (val pair = expectOptionalSequenceField(value, "entities")) {
            null -> emptyList()
            else -> {
                val (entityList, path) = pair
                entityList.mapIndexed { index, entity ->
                    val entityPath = path.child(ValuePathSegment.SequenceElement(index.toLong()))
                    val name = expectStringField(entity, "name", entityPath)
                    val replacement = expectStringField(entity, "replacement", entityPath)
                    if (replacement.contains('<')) {
                        throw MaterializationException(
                            MaterializationFailureKind.UNREPRESENTABLE,
                            path = entityPath.child(ValuePathSegment.ObjectValue("replacement")),
                            valueKind = consema.core.Kind.String,
                        )
                    }
                    EntityRecord(name, replacement, entityPath)
                }
            }
        }
        val root = ElementRecord.validate(rootValue, rootPath, analyzed)
        return XmlRecord(declaration, entities, root)
    }

    fun expectStringField(value: PortableValue, name: String, path: ValuePath): String {
        val objectValue = asObject(value, path)
        val field = objectValue.get(name)
            ?: throw MaterializationException(
                MaterializationFailureKind.INVALID_REQUEST,
                reason = "missing record field",
            )
        return (field as? PvString)?.value
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path.child(ValuePathSegment.ObjectValue(name)),
                valueKind = field.kind,
            )
    }

    /** Fetches one object field of any kind (the Rust
     * expect_object_field, materialization.rs:1239-1256). */
    fun expectField(value: PortableValue, name: String, path: ValuePath): PortableValue {
        val objectValue = asObject(value, path)
        return objectValue.get(name)
            ?: throw MaterializationException(
                MaterializationFailureKind.INVALID_REQUEST,
                reason = "missing record field",
            )
    }

    /** Fetches one object field whose value must be an Object. */
    fun expectObjectField(value: PortableValue, name: String, path: ValuePath): PvObject {
        val field = expectField(value, name, path)
        return field as? PvObject
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path.child(ValuePathSegment.ObjectValue(name)),
                valueKind = field.kind,
            )
    }

    /** Fetches an optional object field from the record root
     * (materialization.rs:1258-1266). */
    fun expectOptionalObjectField(
        value: PortableValue,
        name: String,
    ): Pair<PortableValue, ValuePath>? {
        val objectValue = asObject(value, ValuePath.root())
        val field = objectValue.get(name) ?: return null
        val path = ValuePath.root().child(ValuePathSegment.ObjectValue(name))
        return field to path
    }

    fun expectOptionalStringField(
        value: PortableValue,
        name: String,
        path: ValuePath,
    ): String? {
        val objectValue = value as? PvObject ?: return null
        val field = objectValue.get(name) ?: return null
        if (field is PvNull) {
            return null
        }
        return (field as? PvString)?.value
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path.child(ValuePathSegment.ObjectValue(name)),
                valueKind = field.kind,
            )
    }

    fun expectOptionalBooleanField(
        value: PortableValue,
        name: String,
        path: ValuePath,
    ): Boolean? {
        val objectValue = value as? PvObject ?: return null
        val field = objectValue.get(name) ?: return null
        if (field is PvNull) {
            return null
        }
        return (field as? PvBoolean)?.value
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path.child(ValuePathSegment.ObjectValue(name)),
                valueKind = field.kind,
            )
    }

    fun expectOptionalSequenceField(
        value: PortableValue,
        name: String,
    ): Pair<List<PortableValue>, ValuePath>? {
        val objectValue = value as? PvObject ?: return null
        val field = objectValue.get(name) ?: return null
        val path = ValuePath.root().child(ValuePathSegment.ObjectValue(name))
        val sequence = (field as? PvArray)?.items()
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path,
                valueKind = field.kind,
            )
        return sequence to path
    }

    private fun asObject(value: PortableValue, path: ValuePath): PvObject =
        value as? PvObject
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path,
                valueKind = value.kind,
            )
}

private object ElementRecord {
    fun validate(
        value: PortableValue,
        path: ValuePath,
        analyzed: MutableList<ValuePath>,
    ): XmlElementRecord {
        analyzed.add(path)
        val (namespace, local) = expectExpandedName(value, path)
        val namespaces = when (val pair = Record.expectOptionalSequenceField(value, "namespaces")) {
            null -> emptyList()
            else -> {
                val (bindings, bindingsPath) = pair
                bindings.mapIndexed { index, binding ->
                    val bindingPath =
                        bindingsPath.child(ValuePathSegment.SequenceElement(index.toLong()))
                    val prefix = Record.expectOptionalStringField(binding, "prefix", bindingPath)
                    val uri = Record.expectStringField(binding, "uri", bindingPath)
                    prefix to uri
                }
            }
        }
        val attributes = when (val pair = Record.expectOptionalSequenceField(value, "attributes")) {
            null -> emptyList()
            else -> {
                val (attributeList, attributesPath) = pair
                attributeList.mapIndexed { index, attribute ->
                    val attributePath =
                        attributesPath.child(ValuePathSegment.SequenceElement(index.toLong()))
                    val (attrNamespace, attrLocal) = expectExpandedName(attribute, attributePath)
                    val valueText = Record.expectStringField(attribute, "value", attributePath)
                    AttributeRecord(attrNamespace, attrLocal, valueText, attributePath)
                }
            }
        }
        val content = when (val pair = Record.expectOptionalSequenceField(value, "content")) {
            null -> emptyList()
            else -> {
                val (contentList, contentPath) = pair
                contentList.mapIndexed { index, item ->
                    val itemPath =
                        contentPath.child(ValuePathSegment.SequenceElement(index.toLong()))
                    val itemObject = asObject(item, itemPath)
                    if (itemObject.get("expanded-name") != null) {
                        ContentRecord.Element(
                            validate(item, itemPath, analyzed),
                            itemPath,
                        )
                    } else {
                        when (val kind = Record.expectStringField(item, "kind", itemPath)) {
                            "text" -> {
                                val fragmentsPath = itemPath
                                    .child(ValuePathSegment.ObjectValue("fragments"))
                                val fragmentsValue =
                                    Record.expectField(item, "fragments", fragmentsPath)
                                val fragmentsSequence = (fragmentsValue as? PvArray)?.items()
                                    ?: throw MaterializationException(
                                        MaterializationFailureKind.UNREPRESENTABLE,
                                        path = fragmentsPath,
                                        valueKind = fragmentsValue.kind,
                                    )
                                val fragments = fragmentsSequence.mapIndexed { fragmentIndex, fragment ->
                                    val fragmentPath = fragmentsPath
                                        .child(ValuePathSegment.SequenceElement(fragmentIndex.toLong()))
                                    when (val fragmentKind =
                                        Record.expectStringField(fragment, "kind", fragmentPath)
                                    ) {
                                        "literal" -> FragmentRecord.Literal(
                                            Record.expectStringField(fragment, "text", fragmentPath),
                                        )
                                        "character-reference" -> {
                                            val resolved =
                                                Record.expectStringField(fragment, "resolved", fragmentPath)
                                            if (resolved.length != 1) {
                                                throw MaterializationException(
                                                    MaterializationFailureKind.UNREPRESENTABLE,
                                                    path = fragmentPath,
                                                    valueKind = consema.core.Kind.String,
                                                )
                                            }
                                            FragmentRecord.CharacterReference(resolved[0])
                                        }
                                        "predefined-entity" -> FragmentRecord.PredefinedEntity(
                                            Record.expectStringField(fragment, "name", fragmentPath),
                                            Record.expectStringField(fragment, "resolved", fragmentPath),
                                        )
                                        "general-entity" -> FragmentRecord.GeneralEntity(
                                            Record.expectStringField(fragment, "name", fragmentPath),
                                            Record.expectStringField(fragment, "resolved", fragmentPath),
                                        )
                                        else -> throw MaterializationException(
                                            MaterializationFailureKind.UNREPRESENTABLE,
                                            path = fragmentPath,
                                            valueKind = fragment.kind,
                                        )
                                    }
                                }
                                ContentRecord.Text(fragments, itemPath)
                            }
                            "cdata" -> ContentRecord.Cdata(
                                Record.expectStringField(item, "text", itemPath),
                                itemPath,
                            )
                            "comment" -> ContentRecord.Comment(
                                Record.expectStringField(item, "text", itemPath),
                                itemPath,
                            )
                            "processing-instruction" -> ContentRecord.ProcessingInstruction(
                                Record.expectStringField(item, "target", itemPath),
                                Record.expectOptionalStringField(itemObject, "content", itemPath),
                                itemPath,
                            )
                            else -> throw MaterializationException(
                                MaterializationFailureKind.UNREPRESENTABLE,
                                path = itemPath,
                                valueKind = item.kind,
                            )
                        }
                    }
                }
            }
        }
        val names = HashSet<Pair<String?, String>>()
        for (attribute in attributes) {
            val key = attribute.namespace to attribute.local
            if (!names.add(key)) {
                throw MaterializationException(
                    MaterializationFailureKind.INVALID_REQUEST,
                    reason = "duplicate expanded attribute in input record",
                )
            }
        }
        return XmlElementRecord(namespace, local, namespaces, attributes, content, path)
    }

    fun expectExpandedName(value: PortableValue, path: ValuePath): Pair<String?, String> {
        val name = Record.expectObjectField(value, "expanded-name", path)
        val namePath = path.child(ValuePathSegment.ObjectValue("expanded-name"))
        val namespace = Record.expectOptionalStringField(name, "namespace", namePath)
        val local = Record.expectStringField(name, "local", namePath)
        return namespace to local
    }

    private fun asObject(value: PortableValue, path: ValuePath): PvObject =
        value as? PvObject
            ?: throw MaterializationException(
                MaterializationFailureKind.UNREPRESENTABLE,
                path = path,
                valueKind = value.kind,
            )
}

