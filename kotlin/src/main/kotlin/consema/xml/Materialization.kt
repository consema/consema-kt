/** Deterministic generated-prefix assignment by first-encounter order
 * (materialization.rs:502-526). */
private class PrefixTable {
    private val entries = HashMap<String, String>()
    private var next = 0

    fun prefixFor(namespace: String, default: String?): String {
        if (namespace == default) {
            return ""
        }
        if (namespace == XML_NAMESPACE_URI) {
            return "xml"
        }
        entries[namespace]?.let { return it }
        next += 1
        val prefix = "ns$next"
        entries[namespace] = prefix
        return prefix
    }
}

/** One input location recorded during generation, paired by order with the
 * reparsed document during closure verification (materialization.rs:
 * 528-563). */
private sealed class InputItem {
    abstract val path: ValuePath

    data class Declaration(override val path: ValuePath) : InputItem()
    data class Entity(override val path: ValuePath) : InputItem()
    data class Element(override val path: ValuePath) : InputItem()
    data class NamespaceBinding(override val path: ValuePath) : InputItem()
    data class Attribute(override val path: ValuePath) : InputItem()
    data class Text(override val path: ValuePath) : InputItem()
    data class Fragment(override val path: ValuePath) : InputItem()
    data class Cdata(override val path: ValuePath) : InputItem()
    data class Comment(override val path: ValuePath) : InputItem()
    data class ProcessingInstruction(override val path: ValuePath) : InputItem()

    fun location(): MaterializationInputLocation =
        when (this) {
            is NamespaceBinding -> MaterializationInputLocation.Association(
                AssociationLocation(path, 0L, AssociationRole.ObjectEntry),
            )
            else -> MaterializationInputLocation.Value(path)
        }
}

/** The deterministic canonical writer (materialization.rs:565-900). */
private class Writer(private val limits: MaterializationLimits) {
    val output = java.io.ByteArrayOutputStream()
    val items = ArrayList<InputItem>()
    private var inputNodes = 0
    private val prefixes = PrefixTable()
    /** In-scope bindings as `(prefix, uri)` with null the default
     * namespace; restored by truncation when an element exits. */
    private val scope = ArrayList<Pair<String?, String>>()

    private fun step() {
        inputNodes += 1
        if (inputNodes > limits.maxInputNodes) {
            throw MaterializationException(
                MaterializationFailureKind.RESOURCE_LIMIT,
                name = "input-nodes",
            )
        }
    }

    private fun push(bytes: ByteArray) {
        output.write(bytes)
        if (output.size() > limits.maxOutputBytes) {
            throw MaterializationException(
                MaterializationFailureKind.RESOURCE_LIMIT,
                name = "output-bytes",
            )
        }
    }

    private fun push(text: String) {
        push(text.toByteArray(StandardCharsets.UTF_8))
    }

    /** Spelling prefix for one expanded namespace, using the current scope
     * (materialization.rs:596-621). `""` means unprefixed; null means the
     * URI is not bound in scope and a declaration must be generated. */
    private fun spellingPrefix(uri: String?): String? =
        when {
            uri == null -> ""
            uri == XML_NAMESPACE_URI -> "xml"
            else -> {
                if (scope.asReversed().any { it.first == null && it.second == uri }) {
                    ""
                } else {
                    scope.asReversed()
                        .firstOrNull { it.first != null && it.second == uri }
                        ?.first
                }
            }
        }

    private fun pushEscapedText(text: String) {
        var rest = text
        while (true) {
            val at = rest.indexOfFirst { it == '&' || it == '<' }
            if (at < 0) {
                push(rest)
                return
            }
            push(rest.substring(0, at))
            when (rest[at]) {
                '&' -> push("&amp;")
                else -> push("&lt;")
            }
            rest = rest.substring(at + 1)
        }
    }

    private fun pushEscapedAttribute(text: String) {
        var rest = text
        while (true) {
            val at = rest.indexOfFirst { it == '&' || it == '<' || it == '"' }
            if (at < 0) {
                push(rest)
                return
            }
            push(rest.substring(0, at))
            when (rest[at]) {
                '&' -> push("&amp;")
                '<' -> push("&lt;")
                else -> push("&quot;")
            }
            rest = rest.substring(at + 1)
        }
    }

    fun emitDocument(input: XmlRecord, request: MaterializationRequest) {
        step()
        input.declaration?.let { declaration ->
            items.add(InputItem.Declaration(declaration.path))
            push("<?xml version=\"")
            pushEscapedAttribute(declaration.version)
            push("\"")
            val declaredEncoding = declaration.encoding ?: run {
                if (request.encoding === SourceEncoding.Utf16Le ||
                    request.encoding === SourceEncoding.Utf16Be
                ) {
                    "UTF-16"
                } else {
                    null
                }
            }
            if (declaredEncoding != null) {
                push(" encoding=\"")
                pushEscapedAttribute(declaredEncoding)
                push("\"")
            }
            if (declaration.standalone != null) {
                push(if (declaration.standalone) " standalone=\"yes\"" else " standalone=\"no\"")
            }
            push("?>")
        }
        if (input.entities.isNotEmpty()) {
            push("<!DOCTYPE ")
            val doctypeName = when (val prefix = spellingPrefix(input.root.namespace)) {
                "" -> input.root.local
                null -> {
                    // An unbound root namespace cannot be named in the
                    // DOCTYPE without a declaration; fail honestly.
                    throw MaterializationException(
                        MaterializationFailureKind.UNREPRESENTABLE,
                        path = input.root.path,
                        valueKind = consema.core.Kind.Object,
                    )
                }
                else -> "$prefix:${input.root.local}"
            }
            push(doctypeName)
            push(" [")
            for (entity in input.entities) {
                items.add(InputItem.Entity(entity.path))
                push("<!ENTITY ")
                push(entity.name)
                push(" \"")
                pushEscapedAttribute(entity.replacement)
                push("\">")
            }
            push("]>")
        }
        emitElement(input.root, 0)
        push(request.newline.bytes())
    }

    private fun emitElement(element: XmlElementRecord, depth: Int) {
        step()
        if (depth > limits.maxDepth) {
            throw MaterializationException(
                MaterializationFailureKind.RESOURCE_LIMIT,
                name = "input-depth",
            )
        }
        items.add(InputItem.Element(element.path))
        val scopeLen = scope.size
        // The record's namespace declarations are reproduced verbatim in
        // order; the spelling of names follows the resulting scope.
        for ((prefix, uri) in element.namespaces) {
            scope.add(prefix to uri)
        }
        val elementPrefix = when (val prefix = spellingPrefix(element.namespace)) {
            null -> {
                // Unbound URI in a hand-built record: declare a generated
                // default namespace on this element.
                val uri = element.namespace ?: XML_NAMESPACE_URI
                if (uri == XML_NAMESPACE_URI) {
                    "xml"
                } else {
                    push("<")
                    push(element.local)
                    push(" xmlns=\"")
                    pushEscapedAttribute(uri)
                    push("\"")
                    scope.add(null to uri)
                    items.add(InputItem.NamespaceBinding(element.path))
                    ""
                }
            }
            else -> prefix
        }
        push("<")
        if (elementPrefix.isEmpty()) {
            push(element.local)
        } else {
            push("$elementPrefix:${element.local}")
        }
        for ((prefix, uri) in element.namespaces) {
            items.add(InputItem.NamespaceBinding(element.path))
            if (prefix != null) {
                push(" xmlns:$prefix=\"")
                pushEscapedAttribute(uri)
                push("\"")
            } else {
                push(" xmlns=\"")
                pushEscapedAttribute(uri)
                push("\"")
            }
        }
        for (attribute in element.attributes) {
            items.add(InputItem.Attribute(attribute.path))
            val attributePrefix = when (val prefix = spellingPrefix(attribute.namespace)) {
                null -> {
                    // Unbound attribute namespace: declare a generated
                    // prefix on this element.
                    val uri = attribute.namespace ?: XML_NAMESPACE_URI
                    val generated = prefixes.prefixFor(uri, null)
                    push(" xmlns:$generated=\"")
                    pushEscapedAttribute(uri)
                    push("\"")
                    scope.add(generated to uri)
                    items.add(InputItem.NamespaceBinding(element.path))
                    generated
                }
                else -> prefix
            }
            push(" ")
            if (attributePrefix.isEmpty()) {
                push(attribute.local)
            } else {
                push("$attributePrefix:${attribute.local}")
            }
            push("=\"")
            pushEscapedAttribute(attribute.value)
            push("\"")
        }
        if (element.content.isEmpty()) {
            push("/>")
            restoreScope(scopeLen)
            return
        }
        push(">")
        for (item in element.content) {
            when (item) {
                is ContentRecord.Element -> emitElement(item.element, depth + 1)
                is ContentRecord.Text -> {
                    items.add(InputItem.Text(item.path))
                    for (fragment in item.fragments) {
                        items.add(InputItem.Fragment(item.path))
                        when (fragment) {
                            is FragmentRecord.Literal -> pushEscapedText(fragment.text)
                            is FragmentRecord.CharacterReference ->
                                push("&#${fragment.resolved.code};")

                            is FragmentRecord.PredefinedEntity,
                            is FragmentRecord.GeneralEntity,
                            -> {
                                val entityName = when (fragment) {
                                    is FragmentRecord.PredefinedEntity -> fragment.name
                                    else -> (fragment as FragmentRecord.GeneralEntity).name
                                }
                                push("&$entityName;")
                            }
                        }
                    }
                }
                is ContentRecord.Cdata -> {
                    items.add(InputItem.Cdata(item.path))
                    if (item.text.contains("]]>")) {
                        throw MaterializationException(
                            MaterializationFailureKind.UNREPRESENTABLE,
                            path = item.path,
                            valueKind = consema.core.Kind.String,
                        )
                    }
                    push("<![CDATA[")
                    push(item.text)
                    push("]]>")
                }
                is ContentRecord.Comment -> {
                    items.add(InputItem.Comment(item.path))
                    if (item.text.contains("--") || item.text.endsWith('-')) {
                        throw MaterializationException(
                            MaterializationFailureKind.UNREPRESENTABLE,
                            path = item.path,
                            valueKind = consema.core.Kind.String,
                        )
                    }
                    push("<!--")
                    push(item.text)
                    push("-->")
                }
                is ContentRecord.ProcessingInstruction -> {
                    items.add(InputItem.ProcessingInstruction(item.path))
                    if (item.target.equals("xml", ignoreCase = true) ||
                        item.content?.contains("?>") == true
                    ) {
                        throw MaterializationException(
                            MaterializationFailureKind.UNREPRESENTABLE,
                            path = item.path,
                            valueKind = consema.core.Kind.String,
                        )
                    }
                    push("<?")
                    push(item.target)
                    item.content?.let { content ->
                        push(" ")
                        push(content)
                    }
                    push("?>")
                }
            }
        }
        push("</")
        if (elementPrefix.isEmpty()) {
            push(element.local)
        } else {
            push("$elementPrefix:${element.local}")
        }
        push(">")
        restoreScope(scopeLen)
    }

    /** Restores the in-scope bindings to the length recorded at element
     * entry (the truncation of materialization.rs:840-845). */
    private fun restoreScope(scopeLen: Int) {
        while (scope.size > scopeLen) {
            scope.removeAt(scope.size - 1)
        }
    }
}

