/**
 * Materializes one `xml.element-tree@1` record into a new canonical
 * `xml.1.0-safe@1` document (materialization.rs:36-88). A failure returns no
 * Document, no partial bytes, and no provenance that can be mistaken for a
 * result (RFC 0004 §3).
 */
fun materialize(
    value: PortableValue,
    request: MaterializationRequest,
): MaterializationResult<Document> {
    val analyzed = ArrayList<ValuePath>()
    return try {
        val complete = materializeComplete(value, request, analyzed)
        MaterializationResult.Complete(complete)
    } catch (e: MaterializationException) {
        MaterializationResult.Failed(
            FailedMaterializationAttempt(
                failure = e,
                report = MaterializationReport.new(emptyList(), request.limits),
                analyzedInputPaths = analyzed,
            ),
        )
    }
}

private fun materializeComplete(
    value: PortableValue,
    request: MaterializationRequest,
    analyzed: MutableList<ValuePath>,
): CompleteMaterialization<Document> {
    validateRequest(request)
    val input = Record.validate(value, analyzed)
    val writer = Writer(request.limits)
    writer.emitDocument(input, request)
    val text = writer.output.toByteArray()
    val bytes = encodeText(text, request.encoding, request.limits.maxOutputBytes)
    val document = try {
        parse(
            bytes,
            XmlProfile.SafeV1,
            XmlEncodingSelection.ProfileDefault,
            parseLimits(request.limits),
        )
    } catch (e: XmlFormationException) {
        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
    }
    if (document.formationStatus != consema.document.FormationStatus.Complete) {
        throw MaterializationException(MaterializationFailureKind.FORMATION_FAILED)
    }
    val provenance = verifyClosure(input, document, writer.items, request.limits)
    return CompleteMaterialization(
        document = document,
        fidelity = MaterializationFidelity.Exact,
        report = MaterializationReport.new(emptyList(), request.limits),
        provenance = provenance,
    )
}

private fun validateRequest(request: MaterializationRequest) {
    if (request.targetProfile.id != "xml.1.0-safe" || request.targetProfile.version != 1) {
        throw MaterializationException(MaterializationFailureKind.UNSUPPORTED_PROFILE)
    }
    if (request.style.id != "xml.safe-canonical-document" || request.style.version != 1) {
        throw MaterializationException(MaterializationFailureKind.UNSUPPORTED_STYLE)
    }
    if (request.encoding !== SourceEncoding.Utf8 &&
        request.encoding !== SourceEncoding.Utf16Le &&
        request.encoding !== SourceEncoding.Utf16Be
    ) {
        throw MaterializationException(MaterializationFailureKind.UNSUPPORTED_ENCODING)
    }
    if (request.newline != NewlinePolicy.Lf && request.newline != NewlinePolicy.CrLf) {
        throw MaterializationException(MaterializationFailureKind.UNSUPPORTED_NEWLINE)
    }
}

/** Reparse limits derived from the materialization limits
 * (materialization.rs:109-140). */
private fun parseLimits(limits: MaterializationLimits): XmlParseLimits =
    XmlParseLimits(
        common = ParseLimits(
            maxSourceBytes = limits.maxOutputBytes,
            maxNestingDepth = limits.maxDepth,
            maxTokenCount = limits.maxOutputBytes,
            maxNodeCount = limits.maxInputNodes,
            maxDiagnostics = limits.maxReportEntries,
        ),
        maxDecodedUtf8Bytes = saturatedMultiply(limits.maxOutputBytes, 3),
        maxDecodedScalars = limits.maxOutputBytes,
        maxElementCount = limits.maxInputNodes,
        maxAttributeCount = limits.maxInputNodes,
        maxNamespaceDeclarationCount = limits.maxInputNodes,
        maxMixedContentItems = limits.maxInputNodes,
        maxQnameLength = limits.maxOutputBytes,
        maxNamespaceUriLength = limits.maxOutputBytes,
        maxAttributeValueLength = limits.maxOutputBytes,
        maxCommentLength = limits.maxOutputBytes,
        maxPiLength = limits.maxOutputBytes,
        maxCdataLength = limits.maxOutputBytes,
        maxTextLength = limits.maxOutputBytes,
        maxDtdBytes = limits.maxOutputBytes,
        maxEntityDeclarations = limits.maxInputNodes,
        maxEntityReferences = limits.maxInputNodes,
        maxEntityExpansionDepth = limits.maxDepth,
        maxExpandedEntityBytes = limits.maxOutputBytes,
        maxExpandedEntityScalars = limits.maxOutputBytes,
        maxEntityAmplificationRatio = Long.MAX_VALUE,
        maxRecoveryRegions = limits.maxReportEntries,
    )

private fun saturatedMultiply(left: Int, right: Int): Int =
    if (left > Int.MAX_VALUE / right) Int.MAX_VALUE else left * right

/** Encodes canonical UTF-8 text into the requested output encoding
 * (materialization.rs:142-172). */
private fun encodeText(
    text: ByteArray,
    encoding: SourceEncoding,
    maxOutputBytes: Int,
): ByteArray {
    val output = java.io.ByteArrayOutputStream()
    when (encoding) {
        SourceEncoding.Utf8 -> output.write(text)
        SourceEncoding.Utf16Le, SourceEncoding.Utf16Be -> {
            // The writer only ever emits valid UTF-8.
            val decoded = String(text, StandardCharsets.UTF_8)
            val littleEndian = encoding === SourceEncoding.Utf16Le
            output.write(if (littleEndian) byteArrayOf(0xFF.toByte(), 0xFE.toByte()) else byteArrayOf(0xFE.toByte(), 0xFF.toByte()))
            for (unit in decoded) {
                val high = (unit.code ushr 8) and 0xff
                val low = unit.code and 0xff
                output.write(if (littleEndian) byteArrayOf(low.toByte(), high.toByte()) else byteArrayOf(high.toByte(), low.toByte()))
            }
        }
        else -> throw MaterializationException(MaterializationFailureKind.UNSUPPORTED_ENCODING)
    }
    val bytes = output.toByteArray()
    if (bytes.size > maxOutputBytes) {
        throw MaterializationException(
            MaterializationFailureKind.RESOURCE_LIMIT,
            name = "output-bytes",
        )
    }
    return bytes
}

